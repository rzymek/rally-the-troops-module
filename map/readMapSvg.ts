// Reads a module's map.svg in build scripts and tools: where each space is, without a DOM.
import type {Point} from "./svgPath.ts"

export interface MapSvg {
  /** From the viewBox. */
  width: number
  height: number
  /** Each space's anchor, by id: from `data-anchor="x,y"`, or a hex's `<use id=.. transform="translate(x y)">`. */
  anchors: Map<string, Point>
  /** The hex outline (`<polygon id="hexTemplate">`), relative to a hex's center, if the map has one. */
  hexOutline?: Point[]
}

const attribute = (tag: string, name: string) => new RegExp(`\\s${name}="([^"]*)"`).exec(tag)?.[1]

/** The spaces of a map.svg, as generated by the template's gen-map, or the older modules' hex maps. */
export function readMapSvg(svgText: string): MapSvg {
  const viewBox = attribute(/<svg\b[^>]*>/.exec(svgText)?.[0] ?? "", "viewBox")?.split(/[\s,]+/).map(Number) ?? [0, 0, 0, 0]
  const anchors = new Map<string, Point>()
  for (const [tag] of svgText.matchAll(/<[a-z]+\b[^>]*\sid="[^"]*"[^>]*>/g)) {
    const id = attribute(tag, "id")!
    const anchor = attribute(tag, "data-anchor")
    const translate = /translate\(\s*(-?[\d.]+)[\s,]+(-?[\d.]+)\s*\)/.exec(attribute(tag, "transform") ?? "")
    if (anchor) {
      const [x, y] = anchor.split(",").map(Number)
      anchors.set(id, [x, y])
    } else if (tag.startsWith("<use") && translate) {
      anchors.set(id, [Number(translate[1]), Number(translate[2])])
    }
  }
  const template = /<polygon\b[^>]*\sid="hexTemplate"[^>]*>/.exec(svgText)?.[0]
  const numbers = template ? (attribute(template, "points") ?? "").split(/[\s,]+/).filter(Boolean).map(Number) : []
  const hexOutline = numbers.flatMap((_, i) => i % 2 === 0 ? [[numbers[i], numbers[i + 1]] as Point] : [])
  return {width: viewBox[2], height: viewBox[3], anchors, ...(hexOutline.length > 0 && {hexOutline})}
}
